const { env, Bridge, fs, path, root } = require('./harness.cjs');
const assert = require('node:assert/strict');
const { once } = require('node:events');
(async () => {
  const e = env(); e.context.process.env.ASHUB_TOKEN = 'plugin-test';
  const configDir = e.dir;
  fs.mkdirSync(path.join(configDir, 'extensions'));
  fs.writeFileSync(path.join(configDir, 'extensions', 'sample.mjs'), 'throw new Error("listing must not import")');
  const plugin = e.load('src/plugins.ts').pluginCatalog(path.join(configDir, 'settings.json'))[0];
  const hub = e.hub().startHub({ host: '127.0.0.1', port: 0, webRoot: path.join(root, 'web'), makeBridge: o => {
    const b = new Bridge(o); b.getPluginStatus = () => [{ id: plugin.id, name: 'sample', state: 'loaded' }]; return b;
  } });
  await once(hub.server, 'listening');
  const base = `http://127.0.0.1:${hub.server.address().port}`;
  const headers = { Authorization: 'Bearer plugin-test', 'Content-Type': 'application/json' };
  try {
    assert.equal((await fetch(base + '/api/plugins')).status, 401);
    assert.equal((await fetch(base + '/api/plugins', { method: 'PUT', headers: { ...headers, Origin: 'https://foreign.invalid' }, body: '{}' })).status, 403);
    let r = await fetch(base + '/api/plugins', { headers }); let data = await r.json();
    assert.equal(data.plugins.filter(p => !p.builtin && !p.bundled).length, 1); assert(data.plugins.some(p => p.builtin && p.name === 'OpenAI')); assert.equal(data.plugins[0].sessions.length, 0);
    const included=data.plugins.filter(p=>p.includedApp);
    assert.deepEqual(included.map(p=>p.manifest.id).sort(),['ashub-browser-automation','ashub-image-display','ashub-kimi-coding-plan','ashub-project-management']);
    assert(included.every(p=>p.bundled && !p.enabled && !p.autoApprove));
    const unavailable=included.find(p=>p.manifest.id==='ashub-browser-automation');
    assert(unavailable.compatibilityError);
    const invalidEnable=await fetch(base+'/api/plugins',{method:'PUT',headers,body:JSON.stringify({id:unavailable.id,enabled:true})});
    assert.equal(invalidEnable.status,400,'an unavailable bundled browser cannot be enabled');
    assert.match(await invalidEnable.text(),/browser-pages/);
    assert(!(await (await fetch(base+'/api/plugins',{headers})).json()).plugins.find(p=>p.id===unavailable.id).enabled);
    const project=included.find(p=>p.manifest.id==='ashub-project-management');
    const toggleProject = enabled => fetch(base+'/api/plugins',{method:'PUT',headers,body:JSON.stringify({id:project.id,enabled})});
    assert.equal((await toggleProject(true)).status,200);
    assert.equal((await fetch(base+'/api/config',{method:'PUT',headers,body:JSON.stringify({'ashub.plugins.bundledEnabled':[]})})).status,200);
    let next=(await (await fetch(base+'/api/plugins',{headers})).json()).plugins.find(p=>p.id===project.id);
    assert(next.enabled && !next.autoApprove,'configuration saves cannot change opt-in or approval');
    const consent=await fetch(base+'/api/plugins',{method:'PUT',headers,body:JSON.stringify({id:project.id,autoApprove:true})});
    assert.equal(consent.status,200);
    const deletedApp=await fetch(base+'/api/plugins',{method:'DELETE',headers,body:JSON.stringify({id:project.id})});
    assert.equal(deletedApp.status,200);
    const afterRemove=await deletedApp.json();
    assert(!afterRemove.plugins.some(p=>p.id===project.id));
    assert(afterRemove.restorable.some(p=>p.id===project.manifest.id));
    assert.equal((await fetch(base+'/api/config',{method:'PUT',headers,body:JSON.stringify({'ashub.plugins.bundledRemoved':[]})})).status,200);
    assert(!(await (await fetch(base+'/api/plugins',{headers})).json()).plugins.some(p=>p.id===project.id));
    const restore=await fetch(base+'/api/plugins/install?action=restore',{method:'POST',headers,body:JSON.stringify({id:project.manifest.id})});
    assert.equal(restore.status,200);
    next=(await (await fetch(base+'/api/plugins',{headers})).json()).plugins.find(p=>p.id===project.id);
    assert(next && !next.enabled && !next.autoApprove);
    assert.equal((await toggleProject(false)).status,200);
    await fetch(base + '/sessions', { method: 'POST', headers, body: JSON.stringify({ cwd: e.dir }) });
    r = await fetch(base + '/api/plugins', { headers }); data = await r.json();
    assert.equal(data.plugins[0].sessions[0].state, 'loaded');
    r = await fetch(base + '/api/plugins', { method: 'PUT', headers, body: JSON.stringify({ id: plugin.id, enabled: false }) });
    assert.equal(r.status, 200); data = await r.json();
    assert.equal(data.plugins[0].enabled, false); assert.equal(data.plugins[0].sessions[0].state, 'loaded');
    r = await fetch(base + '/api/config', { method: 'PUT', headers, body: JSON.stringify({ test: true }) }); assert.equal(r.status, 200);
    assert.equal(JSON.parse(fs.readFileSync(path.join(configDir, 'settings.json')))['ashub.plugins.disabled'][0], plugin.id);
    for (const body of [{ id: plugin.id, enabled: 'false' }, { id: 'missing', enabled: true }, null]) {
      assert.equal((await fetch(base + '/api/plugins', { method: 'PUT', headers, body: JSON.stringify(body) })).status, 400);
    }
    assert.equal((await fetch(base + '/api/plugins', { method: 'PUT', headers, body: JSON.stringify({ id: 'builtin:agent', enabled: false }) })).status, 400);
    const auto = async body => fetch(base + '/api/plugins', { method: 'PUT', headers, body: JSON.stringify(body) });
    assert.equal(data.plugins[0].autoApprove, false);
    for (const value of [true, false]) {
      const savedPolicy = await auto({id:plugin.id,autoApprove:value});
      assert.equal(savedPolicy.status,200);
      assert.equal((await savedPolicy.json()).plugins.find(p=>p.id===plugin.id).autoApprove,value);
    }
    await auto({id:plugin.id,autoApprove:true});
    assert.equal((await fetch(base+'/api/config',{method:'PUT',headers,body:JSON.stringify({test:true,'ashub.plugins.autoApprove':[]})})).status,200);
    assert((JSON.parse(fs.readFileSync(path.join(configDir,'settings.json'))))['ashub.plugins.autoApprove'].includes(plugin.id),'stale global config cannot reset plugin consent');
    await auto({id:plugin.id,autoApprove:false});
    for(const body of [{id:plugin.id,autoApprove:'true'},{id:plugin.id,autoApprove:true,enabled:true},{id:'builtin:agent',autoApprove:true},{id:'missing',autoApprove:true}])
      assert.equal((await auto(body)).status,400);
    assert.equal((await fetch(base+'/api/plugins',{method:'PUT',body:JSON.stringify({id:plugin.id,autoApprove:true})})).status,401);
    assert.equal((await fetch(base+'/api/plugins',{method:'PUT',headers:{...headers,Origin:'https://foreign.invalid'},body:JSON.stringify({id:plugin.id,autoApprove:true})})).status,403);
    const nativeURL = base + '/api/plugins/config?id=builtin:provider:openai&namespace=providers.openai';
    const native = await (await fetch(nativeURL, { headers })).json();
    const nativeSave = await fetch(base + '/api/plugins/config', { method: 'PUT', headers, body: JSON.stringify({ id: 'builtin:provider:openai', namespace: 'providers.openai', config: { defaultModel: 'fixture' }, revision: native.revision }) });
    assert.equal(nativeSave.status, 200);
    assert.equal(JSON.parse(fs.readFileSync(path.join(configDir, 'settings.json'))).providers.openai.defaultModel, 'fixture');
    assert.equal((await fetch(base + '/api/plugins/config?id=builtin:provider:openai&namespace=providers.deepseek', { headers })).status, 400);
    const codex = await (await fetch(base + '/api/plugins/config?id=builtin:codex-provider&namespace=codex-provider', { headers })).json();
    const beforeCodex = fs.readFileSync(path.join(configDir, 'settings.json'), 'utf8');
    const invalidCodex = await fetch(base + '/api/plugins/config', { method: 'PUT', headers, body: JSON.stringify({ id: 'builtin:codex-provider', namespace: 'codex-provider', config: { models: 'example-model' }, revision: codex.revision }) });
    assert.equal(invalidCodex.status, 400);
    assert.match(await invalidCodex.text(), /codex-provider.models/);
    assert.equal(fs.readFileSync(path.join(configDir, 'settings.json'), 'utf8'), beforeCodex);
    const configURL = base + '/api/plugins/config?id=' + plugin.id + '&namespace=sample';
    assert.equal((await fetch(configURL)).status, 401);
    assert.equal((await fetch(configURL, { method: 'PUT', headers: { ...headers, Origin: 'https://foreign.invalid' }, body: '{}' })).status, 403);
    let config = await (await fetch(configURL, { headers })).json();
    assert.deepEqual(config.config, {});
    let saved = await fetch(base + '/api/plugins/config', { method: 'PUT', headers, body: JSON.stringify({ id: plugin.id, namespace: 'sample', config: { endpoint: 'https://fixture.invalid', limit: 3 }, revision: config.revision }) });
    assert.equal(saved.status, 200); assert.equal(saved.headers.get('cache-control'), 'no-store');
    const stale = await fetch(base + '/api/plugins/config', { method: 'PUT', headers, body: JSON.stringify({ id: plugin.id, namespace: 'sample', config: {}, revision: config.revision }) });
    assert.equal(stale.status, 409);
    assert.equal((await fetch(base + '/api/plugins/config?id=' + plugin.id + '&namespace=providers', { headers })).status, 400);
    assert.equal((await fetch(base + '/api/plugins/config', { method: 'PUT', headers, body: JSON.stringify({ id: plugin.id, namespace: 'sample', config: [], revision: config.revision }) })).status, 400);
    config = await (await fetch(configURL, { headers })).json(); assert.equal(config.config.limit, 3);
    assert.equal(JSON.parse(fs.readFileSync(path.join(configDir, 'settings.json')))['ashub.plugins.disabled'][0], plugin.id);
    const uninstall = (id, options = {}) => fetch(base + '/api/plugins', {
      method: 'DELETE', headers, body: JSON.stringify({ id }), ...options,
    });
    await auto({ id: plugin.id, autoApprove: true });
    assert.equal((await uninstall(plugin.id, { headers: {} })).status, 401);
    assert.equal((await uninstall(plugin.id, { headers: { ...headers, Origin: 'https://foreign.invalid' } })).status, 403);
    assert.equal((await uninstall('builtin:agent')).status, 404);
    assert.equal((await uninstall('../outside')).status, 404);
    const removed = await uninstall(plugin.id);
    assert.equal(removed.status, 200, await removed.clone().text());
    assert(!(await removed.json()).plugins.some(p => p.id === plugin.id));
    assert(!fs.existsSync(path.join(configDir, 'extensions', 'sample.mjs')));
    const remaining = JSON.parse(fs.readFileSync(path.join(configDir, 'settings.json')));
    assert(!remaining['ashub.plugins.disabled'].includes(plugin.id));
    assert(!remaining['ashub.plugins.autoApprove'].includes(plugin.id));
    assert.equal(remaining.sample.limit, 3);
    assert.equal((await uninstall(plugin.id)).status, 404);
    // An explicit reference outside the managed directory is unregistered only.
    const outside = path.join(configDir, 'source.mjs');
    fs.writeFileSync(outside, 'export default () => {}');
    const settingsFile = path.join(configDir, 'settings.json');
    fs.writeFileSync(settingsFile, JSON.stringify({ ...remaining, extensions: [outside] }));
    const external = (await (await fetch(base + '/api/plugins', {headers})).json()).plugins.find(p => p.source === outside);
    assert.equal((await uninstall(external.id)).status, 200);
    assert(fs.existsSync(outside));
    assert.deepEqual(JSON.parse(fs.readFileSync(settingsFile)).extensions, []);
    console.log('PASS plugin removal: authentication, source confinement, settings retention and consent revocation');
    console.log('PASS plugin config HTTP: auth, namespace isolation, JSON validation, conflict protection');
    console.log('PASS plugin HTTP: authentication, origin, status, toggle, stale config, validation');
  } finally { await hub.shutdown(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
